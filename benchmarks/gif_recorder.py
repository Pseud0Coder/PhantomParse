"""Native animated GIF renderer for PhantomParse pull requests.

Only Pillow is required: no ffmpeg, ImageMagick, or browser automation, so GIF
generation never fails on a missing system binary. Frames are rendered from a
deterministic virtual timeline and can be regenerated byte-for-byte on any
machine with the same font available.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import List, Optional, Sequence

from PIL import Image, ImageDraw, ImageFont

BENCH_DIR = Path(__file__).resolve().parent
REPO_ROOT = BENCH_DIR.parent

for _path in (str(REPO_ROOT), str(REPO_ROOT / "src"), str(BENCH_DIR)):
    if _path not in sys.path:
        sys.path.insert(0, _path)

from keystroke_simulator import SCENARIOS, simulate  # noqa: E402
from phantomparse.buffer import KeystrokeBuffer  # noqa: E402
from phantomparse.gatekeeper import SyntacticGatekeeper  # noqa: E402
from phantomparse.staging import StagingBuffer  # noqa: E402

BACKGROUND = "#12131A"
TEXT = "#E6EAF2"
CYAN = "#00F5D4"
PURPLE = "#9B5DE5"
DIM = "#6C7285"
PANEL = "#232633"

WIDTH = 880
HEIGHT = 500
PAD = 28
BODY_TOP = 100
LINE_HEIGHT = 19
MAX_LINES = (HEIGHT - BODY_TOP - 80) // LINE_HEIGHT

WRAP_WIDTH = 88
DEFAULT_DURATION_MS = 110

FONT_CANDIDATES = (
    r"C:\Windows\Fonts\consola.ttf",
    r"C:\Windows\Fonts\lucon.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
    "/System/Library/Fonts/Menlo.ttc",
)


@dataclass
class Frame:
    """One rendered terminal frame."""

    lines: Sequence[str]
    progress: float = 0.0
    accent: str = CYAN
    note: str = ""


@lru_cache(maxsize=8)
def _font(size: int) -> ImageFont.ImageFont:
    for candidate in FONT_CANDIDATES:
        path = Path(candidate)
        if path.exists():
            try:
                return ImageFont.truetype(str(path), size)
            except OSError:
                continue
    return ImageFont.load_default()


def wrap(text: str, width: int = WRAP_WIDTH) -> List[str]:
    """Hard-wrap text to a fixed character width, preserving blank lines."""
    if not text:
        return [""]
    lines: List[str] = []
    for paragraph in text.splitlines():
        if not paragraph:
            lines.append("")
            continue
        while len(paragraph) > width:
            lines.append(paragraph[:width])
            paragraph = paragraph[width:]
        lines.append(paragraph)
    return lines


def _render(frame: Frame, title: str, subtitle: str, footer: str) -> Image.Image:
    image = Image.new("RGB", (WIDTH, HEIGHT), BACKGROUND)
    draw = ImageDraw.Draw(image)

    draw.rounded_rectangle(
        [1, 1, WIDTH - 2, HEIGHT - 2], radius=18, outline=frame.accent, width=2
    )
    draw.text((PAD, 22), title, font=_font(21), fill=CYAN)
    draw.text((PAD, 56), subtitle, font=_font(13), fill=DIM)
    draw.line((PAD, 84, WIDTH - PAD, 84), fill=PANEL)

    y = BODY_TOP
    for line in list(frame.lines)[-MAX_LINES:]:
        color = TEXT
        if line.startswith("$ "):
            color = CYAN
        elif line.startswith("!!"):
            color = PURPLE
        draw.text((PAD, y), line, font=_font(14), fill=color)
        y += LINE_HEIGHT

    bar_y = HEIGHT - 52
    bar_width = WIDTH - 2 * PAD
    draw.rounded_rectangle([PAD, bar_y, WIDTH - PAD, bar_y + 8], radius=4, fill=PANEL)
    filled = int(bar_width * max(0.0, min(1.0, frame.progress)))
    if filled > 0:
        draw.rounded_rectangle(
            [PAD, bar_y, PAD + filled, bar_y + 8], radius=4, fill=frame.accent
        )

    draw.text((PAD, HEIGHT - 32), footer, font=_font(12), fill=DIM)
    if frame.note:
        anchor = "ra"
        draw.text(
            (WIDTH - PAD, HEIGHT - 32),
            frame.note,
            font=_font(12),
            fill=frame.accent,
            anchor=anchor,
        )
    return image


def write_gif(
    frames: Sequence[Frame],
    out_path: Path,
    title: str,
    subtitle: str,
    footer: str,
    duration_ms: int = DEFAULT_DURATION_MS,
) -> Path:
    """Render frames and write an animated GIF to ``out_path``."""
    if not frames:
        raise ValueError("At least one frame is required")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    images = [_render(frame, title, subtitle, footer) for frame in frames]
    images[0].save(
        out_path,
        save_all=True,
        append_images=images[1:],
        duration=duration_ms,
        loop=0,
        optimize=True,
        disposal=2,
    )
    return out_path


def _typed_frames(header: str, text: str, step: int = 4) -> List[Frame]:
    """Frames that reveal ``text`` progressively, like real typing."""
    frames: List[Frame] = []
    visible = ""
    for index, char in enumerate(text, start=1):
        visible += char
        if index % step == 0 or index == len(text):
            progress = index / len(text)
            frames.append(Frame([header, ""] + wrap("> " + visible + "_"), progress))
    return frames


def _task0_frames() -> List[Frame]:
    frames: List[Frame] = [
        Frame(
            [
                "$ python benchmarks/run_bench.py --modes baseline,naive",
                "",
                "loading scenarios: linear, pivot, multi_clause",
                "typing speed: 60 WPM (5 chars/word)",
            ],
            0.06,
        )
    ]

    total_events = 0
    for result in (simulate(scenario) for scenario in SCENARIOS):
        header = f"$ simulate --scenario {result.scenario.key} --wpm {result.scenario.wpm}"
        frames.extend(_typed_frames(header, result.scenario.initial_text))

        if result.scenario.pivot_backspaces:
            frames.append(
                Frame(
                    [
                        header,
                        "",
                        f"!! BACKSPACE x{result.scenario.pivot_backspaces} "
                        f"after {result.scenario.pivot_pause_ms:.0f} ms pause",
                        "",
                    ]
                    + wrap("> " + result.scenario.pivot_text + "_"),
                    1.0,
                    PURPLE,
                    note="pivot",
                )
            )

        total_events += len(result.events)
        frames.append(
            Frame(
                [
                    header,
                    "",
                    f"events={len(result.events)}  chars={result.char_count}  "
                    f"backspaces={result.backspace_count}",
                    f"virtual_duration={result.duration_ms:.0f} ms",
                ]
                + wrap(f"final_prompt={result.final_text!r}"),
                1.0,
                note=result.scenario.key,
            )
        )

    frames.append(
        Frame(
            [
                "$ simulation complete",
                "",
                f"scenarios={len(SCENARIOS)}  events={total_events}",
                "baseline and naive modes ready for benchmarking",
                "",
                "next: commit, push, open PR 0",
            ],
            1.0,
        )
    )
    return frames


def _buffer_lines(buffer: KeystrokeBuffer) -> List[str]:
    """Snapshot lines describing the committed and pending buffer state."""
    recent = " | ".join(event.token for event in buffer.tokens[-5:]) or "(none yet)"
    stream = buffer.text
    if len(stream) > WRAP_WIDTH - 13:
        stream = "..." + stream[-(WRAP_WIDTH - 16):]
    return [
        f"committed  {buffer.token_count} token(s)",
        "  " + recent,
        f"pending    {buffer.pending!r}",
        f"stream     {stream!r}",
    ]


def _task1_frames() -> List[Frame]:
    scenario = next(item for item in SCENARIOS if item.key == "pivot")
    buffer = KeystrokeBuffer()
    header = "$ phantomparse buffer --scenario pivot"

    steps = (
        [("type", char) for char in scenario.initial_text]
        + [("pause", "")]
        + [("back", "") for _ in range(scenario.pivot_backspaces)]
        + [("type", char) for char in scenario.pivot_text]
    )

    frames: List[Frame] = [
        Frame(
            [
                "$ phantomparse buffer --stream stdin",
                "",
                "rule: emit a token only when whitespace or terminal punctuation",
                "closes its right edge, so BPE subwords never flicker mid-word.",
                "pending text is never parsed, staged, or prefetched.",
            ],
            0.03,
        )
    ]

    for index, (kind, char) in enumerate(steps, start=1):
        progress = index / len(steps)
        if kind == "type":
            buffer.feed_char(char)
        elif kind == "back":
            rollback = buffer.feed_backspace()
            if rollback is not None:
                frames.append(
                    Frame(
                        [header, ""]
                        + _buffer_lines(buffer)
                        + [
                            "",
                            f"!! ROLLBACK token_index={rollback.token_index} "
                            f"removed={rollback.removed!r}",
                        ],
                        progress,
                        PURPLE,
                        note="kv truncate",
                    )
                )
                continue
        else:
            frames.append(
                Frame(
                    [header, ""]
                    + _buffer_lines(buffer)
                    + ["", "!! 400 ms idle pause | pending stays uncommitted"],
                    progress,
                    PURPLE,
                    note="pause",
                )
            )
            continue

        if index % 4 == 0 or kind == "back":
            frames.append(
                Frame(
                    [header, ""] + _buffer_lines(buffer),
                    progress,
                    note="typing" if kind == "type" else "backspace",
                )
            )

    buffer.flush()
    frames.append(
        Frame(
            [
                header,
                "",
                f"committed  {buffer.token_count} token(s) on Enter",
                "  " + " | ".join(event.token for event in buffer.tokens),
                f"pending    {buffer.pending!r}",
                "",
                "every committed token has a stable right boundary,",
                "so downstream parsing and staging never see a half word.",
            ],
            1.0,
            note="stable",
        )
    )
    return frames


def _chunk_lines(chunks: Sequence[object], latency_ms: float, backend: str) -> List[str]:
    """Render parsed constituents as compact terminal lines."""
    lines = [f"backend={backend}  chunks={len(chunks)}  parse={latency_ms:.2f} ms"]
    for chunk in chunks:
        marker = "NP" if chunk.kind == "NP" else "PP"
        head = f" head={chunk.head}" if chunk.head else ""
        lines.append(f"  {marker} {chunk.text!r}{head}")
        if len(lines) >= 8:
            break
    return lines


def _task2_frames() -> List[Frame]:
    scenario = next(item for item in SCENARIOS if item.key == "linear")
    gatekeeper = SyntacticGatekeeper(prefer_spacy=False)
    buffer = KeystrokeBuffer()
    header = "$ phantomparse gatekeeper --scenario linear"
    text = scenario.initial_text

    frames: List[Frame] = [
        Frame(
            [
                "$ phantomparse gatekeeper --explain",
                "",
                "closed class  determiners, prepositions, finite verbs",
                "open class    content word runs between closed-class anchors",
                "",
                "rule  NP = determiner + content run",
                "rule  PP = preposition + NP complement",
                "rule  a phrase with no head content word is incomplete",
                "      and is never staged or prefetched.",
                "",
                "budget 15 ms per parse | speculative_read_only=True",
            ],
            0.03,
        )
    ]

    total = len(text)
    for index, char in enumerate(text, start=1):
        buffer.feed_char(char)
        if not buffer.tokens or not (char in " ." or index % 6 == 0):
            continue
        committed = " ".join(event.token for event in buffer.tokens)
        parsed = gatekeeper.parse(committed)
        frames.append(
            Frame(
                [header, ""]
                + wrap(f"stream     {buffer.text!r}")
                + [""]
                + _chunk_lines(parsed.chunks, parsed.latency_ms, parsed.backend),
                index / total,
                note=f"{len(parsed.chunks)} chunk(s)",
            )
        )

    buffer.flush()
    committed = " ".join(event.token for event in buffer.tokens)
    parsed = gatekeeper.parse(committed)
    np_chunks = parsed.by_kind("NP")
    pp_chunks = parsed.by_kind("PP")
    frames.append(
        Frame(
            [
                header,
                "",
                "commit on whitespace and terminal punctuation, so the",
                "parser never sees a half-typed word or stale BPE subword.",
                "",
                f"NP={len(np_chunks)}  PP={len(pp_chunks)}  "
                f"parse={parsed.latency_ms:.2f} ms  "
                f"within_budget={'yes' if parsed.within_budget else 'no'}",
                "",
                "next: stage these read-only chunks in the RAM ring buffer",
            ],
            1.0,
            note="stable",
        )
    )
    return frames


def _staging_lines(staging: StagingBuffer, limit: int = 4) -> List[str]:
    """Snapshot the ring buffer as compact terminal lines."""
    items = staging.snapshot()
    lines = [
        f"staged={len(items)}  ttl={staging.ttl_seconds:.0f}s  "
        f"capacity={staging.max_items}  sent_to_llm=0 tokens"
    ]
    if not items:
        lines.append("  (waiting for the first closed phrase)")
    for item in list(items)[-limit:]:
        lines.append(f"  {item.kind} {item.text!r}")
    return lines


def _stage_committed(
    buffer: KeystrokeBuffer,
    gatekeeper: SyntacticGatekeeper,
    staging: StagingBuffer,
) -> None:
    """Stage the constituents of the committed prefix, mirroring the daemon."""
    committed = " ".join(event.token for event in buffer.tokens)
    if committed:
        staging.stage_chunks(gatekeeper.parse(committed).chunks)


def _task3_frames() -> List[Frame]:
    scenario = next(item for item in SCENARIOS if item.key == "pivot")
    gatekeeper = SyntacticGatekeeper(prefer_spacy=False)
    staging = StagingBuffer()
    buffer = KeystrokeBuffer()
    header = "$ phantomparse stage --scenario pivot"

    steps = (
        [("type", char) for char in scenario.initial_text]
        + [("pause", "")]
        + [("back", "") for _ in range(scenario.pivot_backspaces)]
        + [("type", char) for char in scenario.pivot_text]
    )

    frames: List[Frame] = [
        Frame(
            [
                "$ phantomparse stage --explain",
                "",
                "while typing   gatekeeper phrases -> RAM ring buffer",
                "                 read-only, never sent, so 0 LLM tokens",
                "on Enter       score every staged span against the",
                "                 final prompt, inject >= 0.75, evict the rest",
                "",
                "ttl 30 s | capacity 64 items | verification budget 15 ms",
            ],
            0.03,
        )
    ]

    for index, (kind, char) in enumerate(steps, start=1):
        progress = index / len(steps)
        if kind == "pause":
            frames.append(
                Frame(
                    [header, ""]
                    + _staging_lines(staging)
                    + [
                        "",
                        "!! 400 ms idle pause | spans age in RAM, still 0 tokens",
                    ],
                    progress,
                    PURPLE,
                    note="ttl ticking",
                )
            )
            continue
        if kind == "back":
            rollback = buffer.feed_backspace()
            if rollback is not None and (index % 7 == 0 or rollback.removed):
                frames.append(
                    Frame(
                        [header, ""]
                        + _staging_lines(staging)
                        + [
                            "",
                            f"!! ROLLBACK removed={rollback.removed!r} | "
                            "span stays staged until verification",
                        ],
                        progress,
                        PURPLE,
                        note="pivot",
                    )
                )
            continue

        if buffer.feed_char(char) is not None:
            _stage_committed(buffer, gatekeeper, staging)
            frames.append(
                Frame(
                    [header, ""]
                    + wrap(f"stream     {buffer.text!r}")
                    + [""]
                    + _staging_lines(staging),
                    progress,
                    note=f"{len(staging)} staged",
                )
            )
        elif index % 18 == 0:
            frames.append(
                Frame(
                    [header, ""]
                    + wrap(f"stream     {buffer.text!r}")
                    + [""]
                    + _staging_lines(staging),
                    progress,
                    note="typing",
                )
            )

    buffer.flush()
    _stage_committed(buffer, gatekeeper, staging)
    verification = staging.verify(scenario.final_text)

    score_lines = ["verification on Enter"]
    for entry in verification.scored:
        verdict = "inject" if entry.accepted else "evict "
        score_lines.append(
            f"  {verdict} {entry.item.kind} {entry.item.text!r} "
            f"score={entry.score:.2f}"
        )
    frames.append(
        Frame(
            [header, ""] + score_lines,
            1.0,
            note=f"threshold {verification.threshold:.2f}",
        )
    )
    frames.append(
        Frame(
            [
                header,
                "",
                f"final prompt  {scenario.final_text!r}",
                "",
                f"staged={len(verification.scored)}  "
                f"injected={len(verification.accepted)}  "
                f"evicted={len(verification.rejected)}",
                f"verification={verification.latency_ms:.2f} ms  "
                f"within_budget={'yes' if verification.within_budget else 'no'}",
                "",
                "wasted LLM tokens = 0",
                "the abandoned clause never left the machine,",
                "so a mid-sentence pivot costs nothing.",
            ],
            1.0,
            note="0 wasted",
        )
    )
    return frames


def record_task(task: int, out_path: Optional[Path] = None) -> Path:
    """Generate the GIF that proves a task's feature works."""
    recipes = {
        0: (
            _task0_frames,
            "PhantomParse | Task 0",
            "Baseline simulator: 60 WPM typing across three scenarios",
        ),
        1: (
            _task1_frames,
            "PhantomParse | Task 1",
            "Keystroke buffer: boundary commits and rollback on backspace",
        ),
        2: (
            _task2_frames,
            "PhantomParse | Task 2",
            "Syntactic gatekeeper: closed NP and PP extraction under budget",
        ),
        3: (
            _task3_frames,
            "PhantomParse | Task 3",
            "RAM staging ring buffer: late-bound verification kills pivot waste",
        ),
    }
    if task not in recipes:
        raise ValueError(f"No GIF recipe registered for task {task}")

    build_frames, title, subtitle = recipes[task]
    frames = build_frames()
    target = out_path or (REPO_ROOT / "docs" / "gifs" / f"task-{task}.gif")
    footer = f"PhantomParse | native Pillow renderer | docs/gifs/task-{task}.gif"
    return write_gif(frames, target, title, subtitle, footer)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Render PhantomParse task GIFs")
    parser.add_argument("--task", type=int, default=0, help="Task number to render")
    parser.add_argument("--out", help="Output GIF path")
    args = parser.parse_args(argv)

    target = record_task(args.task, Path(args.out) if args.out else None)
    size_kb = target.stat().st_size / 1024
    print(f"wrote {target} ({size_kb:.1f} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
